PROVENANCE_NOTE = (
    "Original Jarvis test dialogue informed by general interaction patterns such as short "
    "commands, contextual follow-ups, clarification and status reporting; it is not a film quote "
    "or transcript."
)


def _owner(
    turn_id: str,
    act: Literal["command", "query", "correction", "cancel", "confirm"],
    text: str,
    intent: str,
    elicitation: str,
    *,
    alternate: tuple[str, ...] = (),
    slots: dict[str, Scalar] | None = None,
    refers_to: tuple[str, ...] = (),
    requires_context: bool = False,
    policy: Literal["none", "allow", "confirm", "deny"] = "allow",
) -> DialogueTurn:
    return DialogueTurn(
        turn_id=turn_id,
        speaker="owner",
        dialogue_act=act,
        surface_text=text,
        alternate_surfaces=alternate,
        intent_label=intent,
        slots=slots or {},
        refers_to=refers_to,
        requires_context=requires_context,
        expected_policy=policy,
        elicitation=elicitation,
    )


def _assistant(
    turn_id: str,
    act: Literal["clarify", "acknowledge", "completion", "status", "warning"],
    text: str,
    *,
    updates: dict[str, Scalar] | None = None,
) -> DialogueTurn:
    return DialogueTurn(
        turn_id=turn_id,
        speaker="assistant",
        dialogue_act=act,
        surface_text=text,
        state_updates=updates or {},
    )


