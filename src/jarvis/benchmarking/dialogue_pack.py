def build_phase1_dialogue_speech() -> list[DialogueSpeechEntry]:
    """Derive 40 natural owner prompts while keeping scenario splits intact."""
    entries: list[DialogueSpeechEntry] = []
    for scenario in build_phase1_dialogues():
        owner_turns = [turn for turn in scenario.turns if turn.speaker == "owner"]
        for turn in owner_turns:
            index = len(entries) + 1
            condition_slot = (index - 1) % 5
            condition: Literal["quiet-near", "normal-room", "controlled-noise"]
            if condition_slot in {0, 1}:
                condition = "quiet-near"
            elif condition_slot in {2, 3}:
                condition = "normal-room"
            else:
                condition = "controlled-noise"
            entries.append(
                DialogueSpeechEntry(
                    utterance_id=f"tg_{index:03d}",
                    reference=turn.surface_text,
                    alternate_references=turn.alternate_surfaces,
                    elicitation=turn.elicitation or turn.surface_text,
                    intent_label=turn.intent_label or "unknown",
                    scenario_id=scenario.scenario_id,
                    turn_id=turn.turn_id,
                    condition=condition,
                    split=scenario.split,
                    audio_file=f"raw/mixed-v2/tg_{index:03d}.wav",
                    consented=True,
                )
            )
    return entries
